// Writes src/generated/site-domains.json: which public host belongs to which site, taken from the CMS
// (cms_sites.slug + cms_site_settings.website_url) so that adding a site is a CMS edit plus a domain on the
// Vercel project, not a code change. middleware.ts reads the JSON.
//
// Runs in `prebuild`. If the CMS cannot be reached (or the env is missing) the committed JSON is kept and the build
// carries on: a CMS outage must not stop a deploy. The file is committed so that changes are visible in review.
//   node scripts/gen-site-domains.mjs          write the file
//   node scripts/gen-site-domains.mjs --check  exit 1 if the file differs from the CMS (for a manual audit)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const FILE = 'src/generated/site-domains.json';

function loadEnv() {
  const env = { ...process.env };
  if (existsSync('.env.local')) {
    for (const l of readFileSync('.env.local', 'utf8').split(/\r?\n/)) {
      const i = l.indexOf('=');
      if (i > 0 && !l.startsWith('#') && env[l.slice(0, i)] === undefined) env[l.slice(0, i)] = l.slice(i + 1).replace(/^"|"$/g, '');
    }
  }
  return env;
}

async function main() {
  const check = process.argv.includes('--check');
  const env = loadEnv();
  const url = env.NEXT_PUBLIC_SUPABASE_URL, key = env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !key) { console.warn('gen-site-domains: no Supabase env, keeping the committed file'); return 0; }
  const h = { apikey: key, Authorization: `Bearer ${key}` };
  const get = async (p) => { const r = await fetch(`${url}/rest/v1/${p}`, { headers: h, signal: AbortSignal.timeout(15000) }); if (!r.ok) throw new Error(`${p}: HTTP ${r.status}`); return r.json(); };
  let sites, settings;
  try { [sites, settings] = await Promise.all([get('cms_sites?select=id,slug'), get('cms_site_settings?select=site_id,website_url')]); }
  catch (e) { console.warn('gen-site-domains: CMS not reachable (' + e.message + '), keeping the committed file'); return 0; }

  const slugById = new Map(sites.map((s) => [s.id, s.slug]));
  const hosts = {};
  for (const s of settings) {
    if (!s.website_url || !slugById.has(s.site_id)) continue;
    let host; try { host = new URL(s.website_url).hostname.toLowerCase(); } catch { continue; }
    host = host.replace(/^www\./, '');
    if (hosts[host] && hosts[host] !== slugById.get(s.site_id)) throw new Error(`host ${host} claimed by two sites`);
    hosts[host] = slugById.get(s.site_id);
  }
  if (Object.keys(hosts).length < 3) { console.warn('gen-site-domains: suspiciously few hosts (' + Object.keys(hosts).length + '), keeping the committed file'); return 0; }
  const sorted = Object.fromEntries(Object.entries(hosts).sort(([a], [b]) => a.localeCompare(b)));
  const out = JSON.stringify({ _comment: 'Generated by scripts/gen-site-domains.mjs from cms_sites + cms_site_settings.website_url. Do not edit by hand.', hosts: sorted }, null, 2) + '\n';
  const current = existsSync(FILE) ? readFileSync(FILE, 'utf8') : '';
  if (out === current) { console.log('gen-site-domains: up to date (' + Object.keys(sorted).length + ' hosts)'); return 0; }
  if (check) { console.error('gen-site-domains: the committed file differs from the CMS'); return 1; }
  writeFileSync(FILE, out);
  console.log('gen-site-domains: wrote ' + Object.keys(sorted).length + ' hosts');
  return 0;
}
process.exitCode = await main();
